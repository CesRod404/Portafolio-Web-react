const PALETTE = {
  k: "#1c1428",
  o: "#ff7a1a",
  t: "#0f6f68",
  y: "#ffe566",
  c: "#f7efd6",
  p: "#4a2f86",
  w: "#fff8e6",
  g: "#3ddecb",
  r: "#e24b4b",
};

export function PixelIcon({ art, className = "", label }) {
  const rows = art.replace(/^\n/, "").replace(/\n$/, "").split("\n");
  const height = rows.length;
  const width = Math.max(...rows.map((row) => row.length));
  const rects = [];

  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x += 1) {
      const fill = PALETTE[row[x]];
      if (!fill) continue;
      rects.push(
        <rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" fill={fill} />,
      );
    }
  });

  return (
    <svg
      viewBox={`0 0 ${width} ${height}`}
      className={className ? `pixel-icon ${className}` : "pixel-icon"}
      shapeRendering="crispEdges"
      aria-hidden={label ? undefined : true}
      role={label ? "img" : undefined}
      aria-label={label}
    >
      {rects}
    </svg>
  );
}

export function PlanetMark({ className = "planet" }) {
  return (
    <svg viewBox="0 0 36 36" className={className} aria-hidden="true">
      <circle cx="18" cy="18" r="8" fill="#3ddecb" stroke="#1c1428" strokeWidth="2" />
      <ellipse
        cx="18"
        cy="18"
        rx="14"
        ry="5.5"
        fill="none"
        stroke="#ff7a1a"
        strokeWidth="2"
        transform="rotate(-28 18 18)"
      />
      <circle cx="15" cy="16" r="1.6" fill="#fff8e6" />
    </svg>
  );
}

